#!/usr/bin/env node
// Writes input/fsh/generated/loader-codesystems.fsh: the core IG's ehealth-system and
// ehealth-program CodeSystems, at the version sushi-config.yaml depends on, in a Bundle the loader reads.
// Usage: node scripts/make-codesystems.js [repo]
// Run by scripts/publish.sh and the GitHub workflow before every build; the output is gitignored.
// Reads the package from the FHIR cache, or downloads it from the registry when it is not cached.
const fs = require('fs');
const path = require('path');
const os = require('os');
const zlib = require('zlib');
const crypto = require('crypto');

const REPO = process.argv[2] || '.';
const CORE = 'dk.ehealth.sundhed.fhir.ig.core';
const IDS = ['ehealth-system', 'ehealth-program'];
const REGISTRY = 'https://packages.fhir.org';

function coreVersion() {
  const config = fs.readFileSync(path.join(REPO, 'sushi-config.yaml'), 'utf8');
  const match = config.match(new RegExp(`^  ${CORE.replace(/\./g, '\\.')}:\\s*\\n\\s+version:\\s*(\\S+)`, 'm'));
  if (!match) throw new Error(`No ${CORE} version in sushi-config.yaml`);
  return match[1];
}

function fromCache(version) {
  const cache = process.env.FHIR_PACKAGE_CACHE || path.join(os.homedir(), '.fhir', 'packages');
  const pkg = path.join(cache, `${CORE}#${version}`, 'package');
  if (!IDS.every(id => fs.existsSync(path.join(pkg, `CodeSystem-${id}.json`)))) return null;
  return Object.fromEntries(IDS.map(id => [id, fs.readFileSync(path.join(pkg, `CodeSystem-${id}.json`), 'utf8')]));
}

function untar(buf) {
  const files = {};
  for (let at = 0; at + 512 <= buf.length;) {
    const header = buf.subarray(at, at + 512);
    if (header.every(b => b === 0)) break;
    const field = (from, len) => header.subarray(from, from + len).toString('utf8').replace(/\0.*$/s, '');
    const name = [field(345, 155), field(0, 100)].filter(Boolean).join('/');
    const size = parseInt(field(124, 12).trim() || '0', 8);
    files[name] = buf.subarray(at + 512, at + 512 + size);
    at += 512 + Math.ceil(size / 512) * 512;
  }
  return files;
}

async function fromRegistry(version) {
  const meta = await fetch(`${REGISTRY}/${CORE}`, { headers: { accept: 'application/json' } });
  if (!meta.ok) throw new Error(`${REGISTRY}/${CORE}: HTTP ${meta.status}`);
  const dist = (await meta.json()).versions?.[version]?.dist;
  if (!dist) throw new Error(`${CORE}#${version} is not in ${REGISTRY}`);
  const res = await fetch(`${REGISTRY}/${CORE}/${version}`);
  if (!res.ok) throw new Error(`${REGISTRY}/${CORE}/${version}: HTTP ${res.status}`);
  const tgz = Buffer.from(await res.arrayBuffer());
  const sha1 = crypto.createHash('sha1').update(tgz).digest('hex');
  if (dist.shasum && sha1 !== dist.shasum) throw new Error(`${CORE}#${version}: shasum ${sha1}, registry says ${dist.shasum}`);
  const files = untar(zlib.gunzipSync(tgz));
  return Object.fromEntries(IDS.map(id => {
    const file = files[`package/CodeSystem-${id}.json`];
    if (!file) throw new Error(`${CORE}#${version} has no CodeSystem-${id}.json`);
    return [id, file.toString('utf8')];
  }));
}

function render(version, json) {
  const q = s => JSON.stringify(s); // FSH strings escape like JSON
  const out = [`// GENERATED by scripts/make-codesystems.js from ${CORE}#${version}. Do not edit.`, ''];
  for (const id of IDS) {
    const cs = JSON.parse(json[id]);
    out.push(`Instance: cs-${id}`, 'InstanceOf: CodeSystem', 'Usage: #inline',
      `* id = ${q(cs.id)}`, `* url = ${q(cs.url)}`, `* version = ${q(cs.version)}`, `* name = ${q(cs.name)}`,
      `* status = #${cs.status}`, `* content = #${cs.content}`, `* caseSensitive = ${cs.caseSensitive}`);
    for (const concept of cs.concept || []) {
      if (concept.concept) throw new Error(`${id}: nested concepts are not handled`);
      out.push(`* concept[+].code = #${q(concept.code)}`);
      if (concept.display) out.push(`* concept[=].display = ${q(concept.display)}`);
      if (concept.definition) out.push(`* concept[=].definition = ${q(concept.definition)}`);
    }
    out.push('');
  }
  out.push('Instance: loader-codesystems', 'InstanceOf: Bundle', 'Usage: #example',
    'Title: "Loader code systems"',
    `Description: "Read by the loader, never loaded. The ehealth-system and ehealth-program CodeSystems of ${CORE}: the loader checks the coexistence tags against them, and adds any codes the terminology service lacks."`,
    '* type = #collection');
  for (const id of IDS) {
    out.push(`* entry[+].fullUrl = "http://ehealth.sundhed.dk/testdata/CodeSystem/${id}"`,
      `* entry[=].resource = cs-${id}`);
  }
  return out.join('\n') + '\n';
}

(async () => {
  const version = coreVersion();
  const cached = fromCache(version);
  const json = cached || await fromRegistry(version);
  const dir = path.join(REPO, 'input', 'fsh', 'generated');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'loader-codesystems.fsh'), render(version, json));
  console.log(`Wrote ${IDS.length} CodeSystems from ${CORE}#${version} (${cached ? 'package cache' : REGISTRY})`);
})().catch(e => { console.error(e.message); process.exit(1); });
