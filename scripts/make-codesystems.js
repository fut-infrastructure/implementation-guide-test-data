#!/usr/bin/env node
// Writes input/fsh/generated/loader-codesystems.fsh: the core IG's ehealth-system and
// ehealth-program CodeSystems, at the version sushi-config.yaml depends on, in a Bundle the loader reads.
// Usage: node scripts/make-codesystems.js [repo]   Rerun whenever the core IG dependency changes.
const fs = require('fs');
const path = require('path');
const os = require('os');

const REPO = process.argv[2] || '.';
const CORE = 'dk.ehealth.sundhed.fhir.ig.core';
const IDS = ['ehealth-system', 'ehealth-program'];

const config = fs.readFileSync(path.join(REPO, 'sushi-config.yaml'), 'utf8');
const match = config.match(new RegExp(`^  ${CORE.replace(/\./g, '\\.')}:\\s*\\n\\s+version:\\s*(\\S+)`, 'm'));
if (!match) throw new Error(`No ${CORE} version in sushi-config.yaml`);
const version = match[1];
const cache = process.env.FHIR_PACKAGE_CACHE || path.join(os.homedir(), '.fhir', 'packages');
const pkg = path.join(cache, `${CORE}#${version}`, 'package');

const q = s => JSON.stringify(s); // FSH strings escape like JSON
const out = [`// GENERATED by scripts/make-codesystems.js from ${CORE}#${version}. Do not edit.`, ''];
// The published Description names the version the package declares, not the string that resolved
// it: "current$11.0.1" is how an unpublished CI build is referenced, and does not belong in prose.
let declared = version;
for (const id of IDS) {
  const cs = JSON.parse(fs.readFileSync(path.join(pkg, `CodeSystem-${id}.json`), 'utf8'));
  if (cs.version) declared = cs.version;
  out.push(`Instance: cs-${id}`, 'InstanceOf: CodeSystem', 'Usage: #inline',
    `* id = ${q(cs.id)}`, `* url = ${q(cs.url)}`, `* version = ${q(cs.version)}`, `* name = ${q(cs.name)}`,
    `* status = #${cs.status}`, `* content = #${cs.content}`, `* caseSensitive = ${cs.caseSensitive}`);
  for (const concept of cs.concept || []) {
    if (concept.concept) throw new Error(`${id}: nested concepts are not handled`);
    out.push(`* concept[+].code = #${q(concept.code)}`);
    if (concept.display) out.push(`* concept[=].display = ${q(concept.display)}`);
    if (concept.definition) out.push(`* concept[=].definition = ${q(concept.definition)}`);
  }
  out.push('');
}
out.push('Instance: loader-codesystems', 'InstanceOf: Bundle', 'Usage: #example',
  'Title: "Loader code systems"',
  `Description: "Read by the loader, never loaded. The ehealth-system and ehealth-program CodeSystems of ${CORE}#${declared}: the loader checks the coexistence tags against them and adds the codes terminology lacks."`,
  '* type = #collection');
for (const id of IDS) {
  out.push(`* entry[+].fullUrl = "http://ehealth.sundhed.dk/fhir/testdata/CodeSystem/${id}"`,
    `* entry[=].resource = cs-${id}`);
}
const dir = path.join(REPO, 'input', 'fsh', 'generated');
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'loader-codesystems.fsh'), out.join('\n') + '\n');
console.log(`Wrote ${IDS.length} CodeSystems from ${CORE}#${version}`);
